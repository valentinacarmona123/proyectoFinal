    private void btnRetirarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRetirarActionPerformed
        // TODO add your handling code here:
        try {
            // Validar que se haya ingresado una cuenta
            if (txtCuenta.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor ingrese el número de cuenta primero.");
                return;
            }

            int monto = Integer.parseInt(entradaActual);

            // 1. Validaciones básicas del retiro
            if (monto < 10000 || monto > 1000000) {
                JOptionPane.showMessageDialog(this, "El retiro mínimo es $10.000 y el máximo $1.000.000.");
                return;
            }

            if (monto % 10000 != 0) {
                JOptionPane.showMessageDialog(this, "El monto debe ser estrictamente en múltiplos de $10.000.");
                return;
            }

            // 2. Variables para contar billetes a entregar
            int entregar100 = 0;
            int entregar50 = 0;
            int entregar20 = 0;
            int entregar10 = 0;
            int montoRestante = monto;

            // 3. Reglas especiales de billetes obligatorias
            if (monto == 50000) {
                entregar20 = 2;
                entregar10 = 1;
                montoRestante = 0;
            } else if (monto == 100000) {
                entregar50 = 1;
                entregar20 = 2;
                entregar10 = 1;
                montoRestante = 0;
            } else if (monto > 100000) {
                entregar50 = 1;
                entregar20 = 2;
                entregar10 = 1;
                montoRestante -= 100000;
            }

            // 4. Completar el resto con la menor cantidad de billetes posibles (Greedy)
            if (montoRestante > 0) {
                entregar100 += montoRestante / 100000;
                montoRestante %= 100000;

                int extra50 = montoRestante / 50000;
                entregar50 += extra50;
                montoRestante %= 50000;

                int extra20 = montoRestante / 20000;
                entregar20 += extra20;
                montoRestante %= 20000;

                int extra10 = montoRestante / 10000;
                entregar10 += extra10;
            }

            // 5. Mostrar el resultado detallado en la pantalla del cajero
            txtPantalla.setText("=== RETIRO EXITOSO ===\n"
                    + "Monto Solicitado: $" + monto + "\n\n"
                    + "Distribución de Billetes:\n"
                    + "- Billetes de $100.000: " + entregar100 + "\n"
                    + "- Billetes de $50.000: " + entregar50 + "\n"
                    + "- Billetes de $20.000: " + entregar20 + "\n"
                    + "- Billetes de $10.000: " + entregar10);

            entradaActual = ""; // Limpiamos la entrada numérica temporal

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese el monto a retirar usando el teclado numérico en pantalla.");
        }
    }//GEN-LAST:event_btnRetirarActionPerformed

